-- Analyse sales performance over time
-- All three queries below produce the same monthly trend; they just differ in how
-- the date is bucketed/displayed. Pick whichever fits the SQL version and output format you need.

-- Quick Date Functions
-- YEAR()/MONTH() split the date into two separate numeric columns
SELECT
    YEAR(order_date) AS order_year,
    MONTH(order_date) AS order_month,
    SUM(sales_amount) AS total_sales,
    COUNT(DISTINCT customer_key) AS total_customers,
    SUM(quantity) AS total_quantity
FROM gold.fact_sales
WHERE order_date IS NOT NULL
GROUP BY YEAR(order_date), MONTH(order_date)
ORDER BY YEAR(order_date), MONTH(order_date);

-- DATETRUNC()
-- Truncates the date down to the start of its month, keeping a single sortable date column
-- (requires SQL Server 2022+)
SELECT
    DATETRUNC(month, order_date) AS order_date,
    SUM(sales_amount) AS total_sales,
    COUNT(DISTINCT customer_key) AS total_customers,
    SUM(quantity) AS total_quantity
FROM gold.fact_sales
WHERE order_date IS NOT NULL
GROUP BY DATETRUNC(month, order_date)
ORDER BY DATETRUNC(month, order_date);

-- FORMAT()
-- Formats the date as a readable "yyyy-MMM" string (e.g. "2013-Jan"), handy for reports/charts,
-- but note it sorts and groups as TEXT, and FORMAT() is comparatively slow on large tables
SELECT
    FORMAT(order_date, 'yyyy-MMM') AS order_date,
    SUM(sales_amount) AS total_sales,
    COUNT(DISTINCT customer_key) AS total_customers,
    SUM(quantity) AS total_quantity
FROM gold.fact_sales
WHERE order_date IS NOT NULL
GROUP BY FORMAT(order_date, 'yyyy-MMM')
ORDER BY FORMAT(order_date, 'yyyy-MMM');
